const dictionaries: Record<Language, Record<string, string>> = { en, ta, te };
const I18nContext = createContext({
  language: "en" as Language,
  setLanguage: (_language: Language) => {},
  t: (key: string) => dictionaries.en[key] || key,
});
export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem("cc-language");
    return saved === "ta" || saved === "te" ? saved : "en";
  });
  useEffect(() => {
    document.documentElement.lang = language;
    localStorage.setItem("cc-language", language);
  }, [language]);
  const t = (key: string) =>
    dictionaries[language][key] ||
    dictionaries.en[key] ||
    key.replaceAll("_", " ").toLowerCase();
  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}
export const useI18n = () => useContext(I18nContext);
export function LanguageSelect() {
  const { language, setLanguage, t } = useI18n();
  return (
    <select
      className="language-select"
      aria-label={t("language")}
      value={language}
      onChange={(e) => setLanguage(e.target.value as Language)}
    >
      {(["en", "ta", "te"] as const).map((l) => (
        <option key={l} value={l}>
          {t(l)}
        </option>
      ))}
    </select>
  );
}
